<?php
header('Content-Type: text/plain');

$dir = dirname(__DIR__) . '/node_modules';
echo "Checking node_modules folder: $dir\n";

if (is_dir($dir)) {
    echo "node_modules exists!\n";
    
    // Check if next folder exists
    $next_dir = $dir . '/next';
    if (is_dir($next_dir)) {
        echo "next folder exists inside node_modules!\n";
    } else {
        echo "next folder DOES NOT exist inside node_modules!\n";
    }

    // List all folders inside node_modules
    echo "\n=== DIRECTORIES INSIDE NODE_MODULES ===\n";
    $files = scandir($dir);
    $count = 0;
    foreach ($files as $file) {
        if ($file === '.' || $file === '..') continue;
        if (is_dir($dir . '/' . $file)) {
            echo " - $file\n";
            $count++;
        }
    }
    echo "Total packages listed: $count\n";
} else {
    echo "node_modules folder DOES NOT exist at: $dir\n";
}
?>
