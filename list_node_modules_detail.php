<?php
header('Content-Type: text/plain');
if (!is_dir('node_modules')) {
    echo "node_modules directory does not exist!\n";
    exit;
}

echo "Folders inside node_modules:\n";
$files = scandir('node_modules');
$count = 0;
foreach ($files as $file) {
    if ($file != '.' && $file != '..') {
        echo " - $file\n";
        $count++;
        if ($count > 100) {
            echo "... and more files (truncated)\n";
            break;
        }
    }
}

echo "\nChecking node_modules/next:\n";
if (is_dir('node_modules/next')) {
    echo "node_modules/next exists!\n";
    echo "Contents of node_modules/next:\n";
    foreach (scandir('node_modules/next') as $f) {
        if ($f != '.' && $f != '..') {
            echo "   - $f\n";
        }
    }
} else {
    echo "node_modules/next DOES NOT exist!\n";
}

unlink(__FILE__);
?>
